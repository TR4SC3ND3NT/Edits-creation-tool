const UNKNOWN: &str = "##### #...# #...# #...# #...# #...# #####";

fn glyph(c: char) -> Option<&'static str> {
    if c == ' ' {
        return None;
    }
    let c = c.to_ascii_uppercase();
    Some(GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| *rows).unwrap_or(UNKNOWN))
}

/// Width in pixels of `text` drawn at `scale`.
pub fn text_width(text: &str, scale: u32) -> u32 {
    (text.chars().count() as u32 * ADVANCE).saturating_sub(1) * scale
}

/// Draw `text` with its top-left corner at (`x`, `y`). Each font pixel is a
/// `scale` x `scale` square. Pixels outside the image are skipped.
pub fn draw_text(img: &mut RgbaImage, x: i32, y: i32, scale: u32, color: [u8; 4], text: &str) {
    let scale = scale.max(1) as i32;
    let (w, h) = (img.width() as i32, img.height() as i32);
    for (i, c) in text.chars().enumerate() {
        let Some(rows) = glyph(c) else { continue };
        let gx = x + i as i32 * ADVANCE as i32 * scale;
        for (row, bits) in rows.split(' ').enumerate() {
            for (col, bit) in bits.bytes().enumerate() {
                if bit != b'#' {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (gx + col as i32 * scale + dx, y + row as i32 * scale + dy);
                        if px >= 0 && py >= 0 && px < w && py < h {
                            img.put_pixel(px as u32, py as u32, Rgba(color));
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (c, rows) in GLYPHS.iter().copied().chain([('?', UNKNOWN)]) {
            let rows: Vec<&str> = rows.split(' ').collect();
            assert_eq!(rows.len(), GLYPH_H as usize, "{c}");
            assert!(rows.iter().all(|r| r.len() == GLYPH_W as usize && r.bytes().all(|b| b == b'#' || b == b'.')), "{c}");
        }
    }

    #[test]
    fn text_is_drawn_and_clipped() {
        let mut img = RgbaImage::new(20, 9);
        draw_text(&mut img, 1, 1, 1, [255, 255, 255, 255], "f1 xyz long text");
        assert_eq!(img.get_pixel(1, 1).0, [255, 255, 255, 255]); // top-left of F
        assert_eq!(img.get_pixel(0, 0).0, [0, 0, 0, 0]);
        assert_eq!(text_width("ab", 2), 22);
    }
}
